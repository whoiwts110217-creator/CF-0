function chooseLanguage(value) {
  const selected = Object.hasOwn(LOCALES, value) ? value : "en";
  document.documentElement.lang = selected;
  document.documentElement.dataset.language = selected;
  const choice = document.getElementById("current-language");
  if (choice) choice.textContent = selected.toUpperCase();
  for (const {node, english, lead, trail} of sourceNodes) {
    node.nodeValue = lead + (selected === "en" ? english : COPY[english]?.[selected] || english) + trail;
  }
  for (const control of document.querySelectorAll("[data-set-language]")) {
    const active = control.dataset.setLanguage === selected;
    control.setAttribute("aria-current", active ? "true" : "false");
    control.disabled = active;
  }
  const picker = document.getElementById("language-picker");
  if (picker) {
    picker.open = false;
    picker.querySelector("summary")?.setAttribute("aria-label", "Choose language / Elegir idioma / Choisir la langue / Selecionar idioma");
  }
  document.title = selected === "es" ? "Caveman Focus | De la claridad a la acción" : selected === "fr" ? "Caveman Focus | De la clarté à l’action" : selected === "pt" ? "Caveman Focus | Da clareza à ação" : "Caveman Focus | Clarity into Action";
  const url = new URL(location.href);
  if (selected === "en") url.searchParams.delete("lang");
  else url.searchParams.set("lang", selected);
  history.replaceState(null, "", url);
  try { localStorage.setItem("cf0-home-language", selected); } catch { /* private mode */ }
}

