def drawmap(seed='.'): return [[seed]*20 for _ in range(15)]
def setp(m,x,y,c):
 assert 0<=x<20 and 0<=y<15, (x,y)
 assert c in CHARS,c
 m[y][x]=c
def line(m,x1,y1,x2,y2,c):
 if x1==x2:
  for y in range(min(y1,y2),max(y1,y2)+1):setp(m,x1,y,c)
 elif y1==y2:
  for x in range(min(x1,x2),max(x1,x2)+1):setp(m,x,y1,c)
 else: raise ValueError('straight lines only')
def rect(m,x1,y1,x2,y2,c):
 for y in range(y1,y2+1):line(m,x1,y,x2,y,c)

def add(m,points,c):
 for x,y in points:setp(m,x,y,c)

