def art_bytes():
 out=bytearray()
 for name in ART_ORDER:
  for row in T[name]:
   lo=sum(((int(v)&1)<<(7-i)) for i,v in enumerate(row))
   hi=sum(((int(v)>>1)<<(7-i)) for i,v in enumerate(row))
   out.extend((lo,hi))
 return bytes(out)

